"""Install the animated lessons into the app: copies lessons/out/*.mp4 into assets/media/gallery,
makes posters + a highlight reel, rewrites manifest.json and injects GALLERY/REEL into js/matix-media.js.
usage: python3 build_lessons.py <project root> [rendered dir]"""
import os, sys, json, re, subprocess, shutil, time
sys.path.insert(0,os.path.dirname(os.path.abspath(__file__)))
from lessons import LESSONS
ROOT=os.path.abspath(sys.argv[1]); OUT=sys.argv[2] if len(sys.argv)>2 else os.path.join(os.path.dirname(os.path.abspath(__file__)),'out')
A=ROOT+'/app/src/main/assets'; M=A+'/media'
def sh(cmd):
    r=subprocess.run(cmd,stdout=subprocess.PIPE,stderr=subprocess.PIPE,text=True)
    if r.returncode: print(r.stderr[-2000:]); raise SystemExit('failed: '+' '.join(cmd[:6]))
    return r.stdout
def probe(f):
    j=json.loads(sh(['ffprobe','-v','error','-print_format','json','-show_format','-show_streams',f]))
    s=[x for x in j['streams'] if x['codec_type']=='video'][0]
    return float(j['format']['duration']),s['width'],s['height']
X264=['-c:v','libx264','-profile:v','high','-level','4.1','-pix_fmt','yuv420p','-g','60','-colorspace','bt709','-color_primaries','bt709','-color_trc','bt709','-an','-movflags','+faststart']
keep={l[0] for l in LESSONS}|{'reel'}
for d,ext in (('gallery','.mp4'),('posters','.jpg')):
    for f in os.listdir(f'{M}/{d}'):
        if f.endswith(ext) and f[:-len(ext)] not in keep: os.remove(f'{M}/{d}/{f}'); print('removed',d,f)
gal=[]
for lid,cat,title,sub,dur,fn,acc in LESSONS:
    src=f'{OUT}/{lid}.mp4'; dst=f'{M}/gallery/{lid}.mp4'; shutil.copyfile(src,dst)
    sh(['ffmpeg','-y','-v','error','-ss',str(dur-2.6),'-i',src,'-frames:v','1','-vf','scale=960:540:flags=lanczos','-q:v','4',f'{M}/posters/{lid}.jpg'])
    d,w,h=probe(dst)
    gal.append({'id':lid,'cat':cat,'title':title,'sub':sub,'file':f'media/gallery/{lid}.mp4','poster':f'media/posters/{lid}.jpg','dur':round(d,1),'w':w,'h':h,'bytes':os.path.getsize(dst)})
# highlight reel: 2.4 s from the middle of every lesson
reel=f'{M}/gallery/reel.mp4'; cmd=['ffmpeg','-y','-v','error']; fc=[]; CL=2.4
for i,l in enumerate(LESSONS):
    cmd+=['-ss',f'{l[4]*0.5:.2f}','-t',str(CL),'-i',f'{OUT}/{l[0]}.mp4']
    fc.append(f'[{i}:v]scale=960:540:flags=lanczos,setsar=1,fps=30,format=yuv420p,fade=t=in:st=0:d=0.3,fade=t=out:st={CL-0.3}:d=0.3[v{i}]')
fc.append(''.join(f'[v{i}]' for i in range(len(LESSONS)))+f'concat=n={len(LESSONS)}:v=1:a=0[out]')
sh(cmd+['-filter_complex',';'.join(fc),'-map','[out]']+X264+['-preset','slow','-crf','23','-maxrate','3000k','-bufsize','6000k',reel])
sh(['ffmpeg','-y','-v','error','-ss','12','-i',f'{OUT}/fraction_intro.mp4','-frames:v','1','-vf','scale=1280:720:flags=lanczos','-q:v','4',f'{M}/posters/reel.jpg'])
REEL={'file':'media/gallery/reel.mp4','poster':'media/posters/reel.jpg','dur':round(probe(reel)[0],1),'bytes':os.path.getsize(reel)}
man=json.load(open(M+'/manifest.json'))
man.update(version='1.0.2',generated=time.strftime('%Y-%m-%d'),
  note='Animated lessons are original kinetic-typography videos drawn frame by frame in code (Python + pycairo, x264). Muted H.264 MP4.',
  gallery=gal,reel=REEL)
tot=0
for r,_,fs in os.walk(M):
    for f in fs: tot+=os.path.getsize(os.path.join(r,f))
man['total_bytes']=tot
json.dump(man,open(M+'/manifest.json','w'),ensure_ascii=False,indent=1)
js=A+'/js/matix-media.js'; s=open(js,encoding='utf-8').read()
slim=[{k:v for k,v in g.items() if k!='bytes'} for g in gal]
block='/* @@GALLERY_BEGIN@@ (generated by tools/media/lessons/build_lessons.py) */\nvar GALLERY='+json.dumps(slim,ensure_ascii=False)+';\nvar REEL='+json.dumps({k:REEL[k] for k in ('file','poster','dur')})+';\n/* @@GALLERY_END@@ */'
s2=re.sub(r'/\* @@GALLERY_BEGIN@@.*?@@GALLERY_END@@ \*/',lambda m:block,s,flags=re.S); assert s2!=s
open(js,'w',encoding='utf-8').write(s2)
print(f'lessons {sum(g["bytes"] for g in gal)/1e6:.1f} MB, reel {REEL["bytes"]/1e6:.1f} MB, media total {tot/1e6:.1f} MB')
