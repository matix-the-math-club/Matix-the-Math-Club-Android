"""Install the rendered course into the app.
usage: python3 build_course.py <project root> <rendered dir>
 - copies <id>.mp4 into app/src/main/assets/media/lessons/ and makes a 640x360 poster <id>.jpg next to it
 - writes the @@COURSE@@ block in app/src/main/assets/js/matix-course.js (grades, lessons, quizzes)"""
import os, sys, json, re, shutil, subprocess
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import curriculum as Cu
from pkit import ffmpeg_exe
ROOT, SRC = os.path.abspath(sys.argv[1]), sys.argv[2]
DST = ROOT + '/app/src/main/assets/media/lessons'
os.makedirs(DST, exist_ok=True)
FF = ffmpeg_exe()
out, tot, keep = [], 0, set()
for l in Cu.LESSONS:
    lid = l['id']; src = f'{SRC}/{lid}.mp4'
    if not os.path.exists(src): print('missing', lid); continue
    shutil.copyfile(src, f'{DST}/{lid}.mp4')
    sc = Cu.build(l); dur = sum(d for d, _ in sc)
    at = sc[0][0] + sc[1][0] * 0.75
    subprocess.run([FF, '-y', '-v', 'error', '-ss', f'{at:.2f}', '-i', src, '-frames:v', '1', '-vf', 'scale=640:360:flags=lanczos', '-q:v', '5', f'{DST}/{lid}.jpg'], check=True)
    keep |= {lid + '.mp4', lid + '.jpg'}
    tot += os.path.getsize(f'{DST}/{lid}.mp4') + os.path.getsize(f'{DST}/{lid}.jpg')
    out.append({'id': lid, 'grade': l['grade'], 'title': l['title'], 'sub': l['sub'], 'file': f'media/lessons/{lid}.mp4',
                'poster': f'media/lessons/{lid}.jpg', 'dur': round(dur, 1), 'quiz': [[q, a, w] for q, a, w in l['quiz']]})
for f in os.listdir(DST):
    if f not in keep: os.remove(f'{DST}/{f}'); print('removed', f)
data = {'grades': [list(g) for g in Cu.GRADES if any(x['grade'] == g[0] for x in out)], 'lessons': out}
js = ROOT + '/app/src/main/assets/js/matix-course.js'
s = open(js, encoding='utf-8').read()
block = '/* @@COURSE_BEGIN@@ (generated by tools/media/course/build_course.py) */\nvar COURSE=' + json.dumps(data, ensure_ascii=False) + ';\n/* @@COURSE_END@@ */'
s2 = re.sub(r'/\* @@COURSE_BEGIN@@.*?@@COURSE_END@@ \*/', lambda m: block, s, flags=re.S)
assert s2 != s or block in s
open(js, 'w', encoding='utf-8').write(s2)
print(f'{len(out)} lessons, {tot / 1e6:.1f} MB')
