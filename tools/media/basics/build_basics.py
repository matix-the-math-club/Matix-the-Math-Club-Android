"""Install the rendered Math Basics lessons into app assets and the Math Motion gallery.
usage: python3 build_basics.py <project root> <rendered dir>
 - copies <id>.mp4 to app/src/main/assets/media/basics/, makes a 960x540 poster <id>.jpg next to it
 - writes the @@BASICS@@ block in app/src/main/assets/js/matix-media.js (appends to GALLERY)"""
import os, sys, json, re, shutil, subprocess
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lessons as Ls
from pkit import ffmpeg_exe
ROOT, SRC = os.path.abspath(sys.argv[1]), sys.argv[2]
DST = ROOT + '/app/src/main/assets/media/basics'
os.makedirs(DST, exist_ok=True)
FF = ffmpeg_exe()
gal, tot = [], 0
for l in Ls.LESSONS:
    lid = l['id']; src = f'{SRC}/{lid}.mp4'
    if not os.path.exists(src): print('missing', lid); continue
    shutil.copyfile(src, f'{DST}/{lid}.mp4')
    scenes = Ls.build(l); dur = sum(d for d, _ in scenes)
    at = scenes[0][0] + scenes[1][0] * 0.8  # late in the first worked example
    subprocess.run([FF, '-y', '-v', 'error', '-ss', f'{at:.2f}', '-i', src, '-frames:v', '1', '-vf', 'scale=960:540:flags=lanczos', '-q:v', '4', f'{DST}/{lid}.jpg'], check=True)
    sz = os.path.getsize(f'{DST}/{lid}.mp4') + os.path.getsize(f'{DST}/{lid}.jpg'); tot += sz
    gal.append({'id': lid, 'cat': l['cat'], 'title': l['title'], 'sub': l['sub'], 'file': f'media/basics/{lid}.mp4',
                'poster': f'media/basics/{lid}.jpg', 'dur': round(dur, 1), 'w': 1920, 'h': 1080})
for f in os.listdir(DST):
    if f.rsplit('.', 1)[0] not in {g['id'] for g in gal}: os.remove(f'{DST}/{f}'); print('removed', f)
js = ROOT + '/app/src/main/assets/js/matix-media.js'
s = open(js, encoding='utf-8').read()
block = ('/* @@BASICS_BEGIN@@ (generated by tools/media/basics/build_basics.py) */\n'
         'var BASICS=' + json.dumps(gal, ensure_ascii=False) + ';\nGALLERY=GALLERY.concat(BASICS);\n/* @@BASICS_END@@ */')
if '@@BASICS_BEGIN@@' in s:
    s = re.sub(r'/\* @@BASICS_BEGIN@@.*?@@BASICS_END@@ \*/', lambda m: block, s, flags=re.S)
else:
    s = s.replace('/* @@GALLERY_END@@ */', '/* @@GALLERY_END@@ */\n' + block, 1)
open(js, 'w', encoding='utf-8').write(s)
print(f'{len(gal)} lessons, {tot / 1e6:.1f} MB in app assets')
